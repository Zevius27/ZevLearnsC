



int main() {

    // Create variables
    int myNum = 5;             // Integer (whole number)
                                    // 2 or 4 bytes
    float myFloatNum = 5.99;   // Floating point number
                                    // 4 bytes
    double myDoubleNum = 5.99 ;   // Double : storing 15 decimal digits
                                    // 8 bytes
    char myLetter = 'D';       // Character
                                    // 1 byte
    printf("%d", myNum);
    printf("%f", myFloatNum);
    printf("%c", myLetter);
    printf("%lf", myDoubleNum);
    
    return  0;
    }
